#!/bin/sh
# Builds each Edge Function that uses the game engine into one self-contained
# index.ts (server.ts + engine/ inlined) to paste into the Supabase dashboard
# editor: Supabase can't import from the game's site. Run after changing a
# server.ts or engine/, then redeploy the function(s) that changed.
set -e
cd "$(dirname "$0")/.."
for fn in pvp economy voice; do
  OUT=supabase/functions/$fn/index.ts
  npx --yes esbuild@0.24.0 supabase/functions/$fn/server.ts --bundle --format=esm --platform=neutral \
    --target=es2022 --minify-whitespace --minify-syntax --external:'https://*' --legal-comments=none --log-level=warning --outfile=$OUT.tmp.js
  {
    echo "// GENERATED by tools/bundle-functions.sh from server.ts + engine/: do not edit by hand."
    echo "// Paste this whole file into the Supabase Edge Function '$fn' (docs/15-server-collection.md)."
    cat $OUT.tmp.js
  } > $OUT
  rm $OUT.tmp.js
  echo "wrote $OUT ($(wc -c < $OUT) bytes)"
done
